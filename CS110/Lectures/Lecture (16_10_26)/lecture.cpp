#include <iostream>
using namespace std;
// Interative Control Statements
// Testing for loop

int main() {
    int i;
    for (i = 0; i < 10; i++) { // for(initialization; condition; increment/decrement) // printing the value of i from 0 to 9
        cout << "i = " << i << endl;
    }
    return 0;
}